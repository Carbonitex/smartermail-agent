public sealed class SealerTests
{
    [Fact]
    public void Round_trip_binds_label_and_context()
    {
        var sealer = new Sealer(RandomNumberGenerator.GetBytes(32));
        var sealedValue = sealer.SealString("secret"u8, "label-a", "p|1");

        Assert.Equal("secret", Encoding.UTF8.GetString(sealer.OpenString(sealedValue, "label-a", "p|1")!));
        Assert.Null(sealer.OpenString(sealedValue, "label-b", "p|1"));   // another use
        Assert.Null(sealer.OpenString(sealedValue, "label-a", "p|2"));   // another row
        Assert.Null(new Sealer(RandomNumberGenerator.GetBytes(32)).OpenString(sealedValue, "label-a", "p|1"));
    }

    [Fact]
    public void Previous_key_opens_but_never_seals()
    {
        var old = RandomNumberGenerator.GetBytes(32);
        var sealedOld = new Sealer(old).SealString("x"u8, "l");
        var rotated = new Sealer(RandomNumberGenerator.GetBytes(32), old);

        Assert.NotNull(rotated.OpenString(sealedOld, "l"));
        Assert.Null(new Sealer(old).OpenString(rotated.SealString("y"u8, "l"), "l"));
    }

    /// <summary>The remember-me bundle's wire format is unchanged by the move onto Sealer.</summary>
    [Fact]
    public void Empty_context_matches_the_original_resume_format()
    {
        var key = RandomNumberGenerator.GetBytes(32);
        var data = new Sealer(key).Seal("payload"u8, "sma-resume-v1");

        var label = Encoding.ASCII.GetBytes("sma-resume-v1");
        var aad = label.Concat(new[] { data[0], data[1] }).ToArray();
        var plaintext = new byte[data.Length - 2 - 12 - 16];
        using var aes = new AesGcm(key, 16);
        aes.Decrypt(data.AsSpan(2, 12), data.AsSpan(14, plaintext.Length), data.AsSpan(14 + plaintext.Length, 16), plaintext, aad);

        Assert.Equal(0x01, data[0]);
        Assert.Equal(SHA256.HashData(key)[0], data[1]);
        Assert.Equal("payload", Encoding.UTF8.GetString(plaintext));
    }
}

public sealed class ProfileCryptoTests
{
    [Fact]
    public void Transcript_seal_opens_only_with_the_private_key_and_context()
    {
        using var recipient = ECDiffieHellman.Create(ECCurve.NamedCurves.nistP256);
        var spki = Base64Url.Encode(recipient.ExportSubjectPublicKeyInfo());
        Assert.True(ProfileCrypto.IsValidPublicKey(spki));

        var sealedValue = ProfileCrypto.SealToPublicKey("hello report"u8, spki, "task-run|p|r");
        Assert.Equal("hello report", Encoding.UTF8.GetString(ProfileCrypto.OpenWithPrivateKey(sealedValue, recipient, "task-run|p|r")));

        Assert.ThrowsAny<CryptographicException>(() => ProfileCrypto.OpenWithPrivateKey(sealedValue, recipient, "task-run|p|other"));
        using var stranger = ECDiffieHellman.Create(ECCurve.NamedCurves.nistP256);
        Assert.ThrowsAny<CryptographicException>(() => ProfileCrypto.OpenWithPrivateKey(sealedValue, stranger, "task-run|p|r"));
    }

    /// <summary>
    /// The browser opens what the server seals: a vector checked in for the frontend's node tests
    /// (dev/test/vault.test.mjs). Regenerate with UPDATE_VECTORS=1.
    /// </summary>
    [Fact]
    public void Transcript_vector_for_the_browser()
    {
        var path = Path.Combine(RepoRoot(), "src", "Agent", "wwwroot", "dev", "test", "vectors", "transcript.json");
        if (Environment.GetEnvironmentVariable("UPDATE_VECTORS") == "1" || !File.Exists(path))
        {
            using var key = ECDiffieHellman.Create(ECCurve.NamedCurves.nistP256);
            const string context = "task-run|profile-123|run-456";
            const string plaintext = "{\"final\":\"Three unread messages, none urgent.\"}";
            var vector = new
            {
                note = "Generated by ProfileCryptoTests.Transcript_vector_for_the_browser; opened by vault.test.mjs.",
                privateKeyPkcs8 = Base64Url.Encode(key.ExportPkcs8PrivateKey()),
                publicKey = Base64Url.Encode(key.ExportSubjectPublicKeyInfo()),
                context,
                plaintext,
                sealedValue = ProfileCrypto.SealToPublicKey(Encoding.UTF8.GetBytes(plaintext), Base64Url.Encode(key.ExportSubjectPublicKeyInfo()), context),
            };
            Directory.CreateDirectory(Path.GetDirectoryName(path)!);
            File.WriteAllText(path, System.Text.Json.JsonSerializer.Serialize(vector, new System.Text.Json.JsonSerializerOptions { WriteIndented = true }) + "\n");
        }

        var json = System.Text.Json.JsonDocument.Parse(File.ReadAllText(path)).RootElement;
        using var recipient = ECDiffieHellman.Create();
        recipient.ImportPkcs8PrivateKey(Base64Url.Decode(json.GetProperty("privateKeyPkcs8").GetString())!, out _);
        var opened = ProfileCrypto.OpenWithPrivateKey(json.GetProperty("sealedValue").GetString()!, recipient,
            json.GetProperty("context").GetString()!);
        Assert.Equal(json.GetProperty("plaintext").GetString(), Encoding.UTF8.GetString(opened));
    }

    private static string RepoRoot()
    {
        var dir = new DirectoryInfo(AppContext.BaseDirectory);
        while (dir is not null && !File.Exists(Path.Combine(dir.FullName, "SmarterMail.slnx")))
            dir = dir.Parent;
        return dir?.FullName ?? throw new InvalidOperationException("Repo root not found.");
    }

    [Theory]
    [InlineData(null)]
    [InlineData("")]
    [InlineData("not-base64!!")]
    [InlineData("AAAA")]
    public void Bad_public_keys_are_refused(string? spki) => Assert.False(ProfileCrypto.IsValidPublicKey(spki));

    [Fact]
    public void P384_keys_are_refused()
    {
        using var key = ECDiffieHellman.Create(ECCurve.NamedCurves.nistP384);
        Assert.False(ProfileCrypto.IsValidPublicKey(Base64Url.Encode(key.ExportSubjectPublicKeyInfo())));
    }

    [Fact]
    public void Accounts_key_check_and_recovery_hash()
    {
        var key = RandomNumberGenerator.GetBytes(32);
        var check = ProfileCrypto.AccountsKeyCheck(key);
        Assert.True(ProfileCrypto.AccountsKeyMatches(key, check));
        Assert.False(ProfileCrypto.AccountsKeyMatches(RandomNumberGenerator.GetBytes(32), check));

        var auth = RandomNumberGenerator.GetBytes(32);
        var hash = ProfileCrypto.RecoveryAuthHash(auth);
        Assert.True(ProfileCrypto.RecoveryAuthMatches(auth, hash));
        Assert.False(ProfileCrypto.RecoveryAuthMatches(auth, null));
    }
